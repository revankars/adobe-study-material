#!/usr/bin/env python3
"""Builds the files that index.html loads.

  assets/js/portal.bundle.js  - all portal modules as one classic script
  assets/js/data-bundle.js    - every file under data/, embedded for opening index.html from disk

Run from the project root after editing any file in assets/js/ or data/:

    python3 tools/build_bundle.py

The source modules stay in assets/js/ for editing. index.html loads only the bundles.
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
JS = ROOT / "assets" / "js"

# Dependency order: every module appears after the modules it imports.
ORDER = ["data", "study", "storage", "dashboard", "quiz", "practice-tests",
         "mock-tests", "study-selection", "quick-revision", "app"]

IMPORT_RE = re.compile(r'^import\s+\{([^}]*)\}\s+from\s+"\./([\w-]+)\.js";\s*$')
EXPORT_RE = re.compile(r'^export\s+((?:async\s+)?function\s+(\w+)|(?:const|let|var)\s+(\w+))')

def module_exports(src):
    names = []
    for line in src.splitlines():
        m = EXPORT_RE.match(line)
        if m:
            names.append(m.group(2) or m.group(3))
    return names

def build_portal():
    parts = [
        "/* Generated by tools/build_bundle.py. Do not edit; edit the modules in assets/js/ instead. */",
    ]
    exports_of = {}
    for name in ORDER:
        src = (JS / f"{name}.js").read_text(encoding="utf8")
        imports, body = [], []
        for line in src.splitlines():
            m = IMPORT_RE.match(line)
            if m:
                names = [n.strip() for n in m.group(1).split(",") if n.strip()]
                imports.append((m.group(2), names))
                continue
            if line.startswith("import "):
                raise SystemExit(f"Unsupported import in {name}.js: {line}")
            body.append(re.sub(r"^export\s+", "", line))
        exports = module_exports(src)
        exports_of[name] = exports
        lines = [f"const NS_{name.replace('-', '_')} = (function () {{"]
        for dep, names in imports:
            lines.append(f"  const {{ {', '.join(names)} }} = NS_{dep.replace('-', '_')};")
        lines += body
        if exports:
            lines.append(f"  return {{ {', '.join(exports)} }};")
        else:
            lines.append("  return {};")
        lines.append("})();")
        parts.append("\n".join(lines))
    out = JS / "portal.bundle.js"
    out.write_text("\n\n".join(parts) + "\n", encoding="utf8")
    return out

def build_data():
    bundle = {}
    for path in sorted((ROOT / "data").rglob("*.json")):
        key = path.relative_to(ROOT).as_posix()
        bundle[key] = json.loads(path.read_text(encoding="utf8"))
    out = JS / "data-bundle.js"
    out.write_text("/* Generated by tools/build_bundle.py. Do not edit; edit files in data/ instead. */\n"
                   "window.PORTAL_DATA = " + json.dumps(bundle, ensure_ascii=False) + ";\n", encoding="utf8")
    return out, len(bundle)

if __name__ == "__main__":
    p = build_portal()
    d, n = build_data()
    print(f"wrote {p.relative_to(ROOT)} and {d.relative_to(ROOT)} ({n} data files)")
